// Writes lib/core/audio/melodies.dart: 12 original 16-note melodies per
// chapter as indices into that chapter's note list (`docs/07` §1).
//
//   dart run tool/gen_melodies.dart
//
// The melodies are composed by rule, not copied from anything: four 4-note
// phrases (statement, answer, the statement moved a step or two, and a
// cadence that lands on the tonic), stepwise motion with the odd skip, chord
// tones on the strong beats of non-pentatonic scales. Seeded with Mulberry32,
// so the output is identical on every machine.
import 'dart:io';

import 'package:arrowchime/core/audio/chapter_sound.dart';
import 'package:arrowchime/core/level/prng.dart';

const _perChapter = 12;
const _phrases = 4;
const _perPhrase = 4;

List<int> compose(ChapterSound s, int number) {
  final rng = Mulberry32(s.chapter * 1000 + number * 7 + 13);
  final top = s.length - 2;
  const bottom = 1;

  int clampNote(int i) => i < bottom ? bottom : (i > top ? top : i);

  // Nearest chord tone to [i] (any note for pentatonic scales).
  int snap(int i) {
    for (var d = 0; d < s.length; d++) {
      for (final c in [i - d, i + d]) {
        if (c >= bottom && c <= top && s.isChordTone(c)) return c;
      }
    }
    return i;
  }

  int nearestTonic(int i) {
    var best = s.tonics.first;
    for (final t in s.tonics) {
      if ((t - i).abs() < (best - i).abs()) best = t;
    }
    return best;
  }

  // Statement: start on a chord tone in the lower-middle, wander by steps.
  final start = snap(clampNote(2 + rng.nextInt(s.length ~/ 2 - 1)));
  final statement = <int>[start];
  for (var i = 1; i < _perPhrase; i++) {
    final roll = rng.nextInt(10);
    final step = roll < 3
        ? 1
        : roll < 6
        ? -1
        : roll < 8
        ? 2
        : -2;
    statement.add(clampNote(statement.last + step));
  }
  if (!s.pentatonic) statement[0] = snap(statement[0]);

  // Answer: contour mirrored, ending on a chord tone that is not the tonic.
  final answer = <int>[
    for (final n in statement) clampNote(2 * statement.first - n + 1),
  ];
  answer[_perPhrase - 1] = snap(answer.last);

  // Third phrase: the statement moved by one or two steps.
  final shift = rng.nextBool() ? 2 : 1;
  final moved = [for (final n in statement) clampNote(n + shift)];

  // Cadence: a short run down or up that lands on the nearest tonic.
  final home = nearestTonic(moved.last);
  final cadence = <int>[];
  for (var i = 0; i < _perPhrase - 1; i++) {
    final remaining = _perPhrase - 1 - i;
    final towards = home > moved.last ? 1 : -1;
    cadence.add(clampNote(home - towards * remaining));
  }
  cadence.add(home);

  final all = [...statement, ...answer, ...moved, ...cadence];
  // Strong beats (0, 4, 8, 12) on chord tones for non-pentatonic scales.
  if (!s.pentatonic) {
    for (var i = 0; i < all.length; i += _perPhrase) {
      all[i] = snap(all[i]);
    }
    all[all.length - 1] = home;
  }
  assert(all.length == _phrases * _perPhrase, 'four phrases of four notes');
  return all;
}

void main() {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_melodies.dart. Do not edit by hand.')
    ..writeln()
    ..writeln('/// 12 original melodies per chapter, as indices into the')
    ..writeln(
      "/// chapter's note list (`ChapterSound.notes`), keyed by chapter.",
    )
    ..writeln('const Map<int, List<List<int>>> chapterMelodies = {');
  for (final s in ChapterSound.all) {
    out.writeln('  ${s.chapter}: [');
    for (var m = 1; m <= _perChapter; m++) {
      out.writeln('    ${compose(s, m)},');
    }
    out.writeln('  ],');
  }
  out.writeln('};');
  File('lib/core/audio/melodies.dart').writeAsStringSync(out.toString());
  stdout.writeln('wrote lib/core/audio/melodies.dart');
}
