  };

  /// Width in pixels of [text] at integer [scale] (6 columns per glyph).
  static int widthOf(String text, int scale) => text.length * 6 * scale - scale;

  /// Draws [text] (upper-cased) with its top-left at `(x, y)`.
  static void draw(Pixmap pm, String text, int x, int y, int scale, int color) {
    var cx = x;
    for (final ch in text.toUpperCase().split('')) {
      final g = _glyphs[ch] ?? _glyphs[' ']!;
      for (var row = 0; row < 7; row++) {
        for (var col = 0; col < 5; col++) {
          if (g[row][col] != '1') continue;
          pm.fillRect(
            cx + col * scale,
            y + row * scale,
            cx + (col + 1) * scale,
            y + (row + 1) * scale,
            color,
          );
        }
      }
      cx += 6 * scale;
    }
  }

  /// Draws [text] centred horizontally in `[0, pm.width)` at row [y].
  static void drawCentered(
    Pixmap pm,
    String text,
    int y,
    int scale,
    int color,
  ) {
    draw(pm, text, (pm.width - widthOf(text, scale)) ~/ 2, y, scale, color);
  }
}
